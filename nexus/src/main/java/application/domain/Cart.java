package application.domain;

import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Represents the provisional selection of products a buyer makes before
 * confirming a purchase. Modeled as a class separate from Order (design
 * decision, see Domain Model.md) because the source document treats
 * "Cart management" as an independent, manageable process (OBJ-07).
 */
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class Cart {

    /**
     * Unique identifier of the cart. SUPUESTO (decision D2): the source document
     * does not list it, but the cart is updated after it is stored, so it needs an
     * identity of its own. It is generated by the persistence adapter when the
     * cart is first saved and never comes from the client.
     */
    private String identifier;
    private Buyer buyer;
    private CartStatus status;
}
